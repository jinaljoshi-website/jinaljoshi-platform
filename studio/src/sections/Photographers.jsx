// studio/src/sections/Photographers.jsx
import { useEffect, useState } from 'react';
import { api } from '../api';
import { T, S, Card, Eyebrow, Field, colors } from '../ui';

const sans    = "'DM Sans', system-ui, sans-serif";
const mono    = "'DM Mono', 'Courier New', monospace";
const display = "'Cormorant Garamond', Georgia, serif";

const rupees = (n) => `₹${Number(n || 0).toLocaleString('en-IN', { maximumFractionDigits: 0 })}`;

export function Photographers() {
  const [data,    setData]    = useState(null);
  const [error,   setError]   = useState('');
  const [success, setSuccess] = useState('');
  const [open,    setOpen]    = useState(null);      // whose sets are expanded
  const [paying,  setPaying]  = useState(null);      // whose payment form is open
  const [form,    setForm]    = useState({ amountInr: '', reference: '', note: '' });
  const [busy,    setBusy]    = useState(false);
  const [history, setHistory] = useState({});

  const load = () => api.get('/api/studio/photographers/earnings')
    .then(setData).catch((e) => setError(e.message));

  useEffect(() => { load(); }, []);

  const openPayment = (p) => {
    setPaying(paying === p.id ? null : p.id);
    setForm({ amountInr: '', reference: '', note: '' });
    setError(''); setSuccess('');
    if (!history[p.id]) {
      api.get(`/api/studio/photographers/${p.id}/payments`)
        .then((d) => setHistory((h) => ({ ...h, [p.id]: d.payments || [] })))
        .catch(() => {});
    }
  };

  const record = async (p) => {
    setBusy(true); setError('');
    try {
      await api.post(`/api/studio/photographers/${p.id}/paid`, form);
      const d = await api.get(`/api/studio/photographers/${p.id}/payments`);
      setHistory((h) => ({ ...h, [p.id]: d.payments || [] }));
      setSuccess(`Recorded ${rupees(form.amountInr)} to ${p.name}.`);
      setForm({ amountInr: '', reference: '', note: '' });
      setPaying(null);
      load();
    } catch (err) { setError(err.message); } finally { setBusy(false); }
  };

  if (!data) return <T.muted>Loading…</T.muted>;

  return (
    <div>
      <Eyebrow>Credits</Eyebrow>
      <T.title>Photographers</T.title>

      {error   && <div style={S.error}>{error}</div>}
      {success && <div style={S.success}>{success}</div>}

      <p style={{ fontFamily: sans, fontSize: 13, color: colors.muted, lineHeight: 1.7, marginBottom: 20, maxWidth: 720 }}>
        What each person's work has brought in directly — tokens somebody spent to open their
        sets — and what you have sent them. Figures are net of GST, which is collected for the
        government rather than earned. Sets opened on a membership are counted but carry no
        figure: that fee buys access to the platform, so it is not the set's earnings. Test
        accounts are excluded. There is no suggested figure and nothing is owed — decide what
        feels right, send it, and log it here so the record is in one place.
      </p>

      <div style={S.statsRow}>
        <div style={S.statCard}>
          <div style={pLabel}>Generated by their work</div>
          <div style={pValue}>{rupees(data.totalGenerated)}</div>
          <div style={pSub}>across every set they shot</div>
        </div>
        <div style={S.statCard}>
          <div style={pLabel}>Sent so far</div>
          <div style={{ ...pValue, color: colors.success }}>{rupees(data.totalPaid)}</div>
          <div style={pSub}>logged payments, all time</div>
        </div>
        <div style={S.statCard}>
          <div style={pLabel}>Opened on memberships</div>
          <div style={{ ...pValue, fontSize: 20 }}>
            {data.photographers.reduce((n, p) => n + p.sets.reduce((m, s) => m + (s.creditUnlocks || 0), 0), 0)}
          </div>
          <div style={pSub}>
            counted, not valued — a membership fee is for the platform, not the set
          </div>
        </div>
      </div>

      {data.photographers.length === 0 ? (
        <T.muted>No photographers credited yet. Add a name when you create or edit a set.</T.muted>
      ) : (
        <div style={{ display: 'grid', gap: 12, marginTop: 20 }}>
          {data.photographers.map((p) => (
            <Card key={p.id}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', gap: 14, flexWrap: 'wrap' }}>
                <div style={{ flex: 1, minWidth: 200 }}>
                  <div style={{ fontFamily: display, fontSize: 20, color: colors.text }}>{p.name}</div>
                  <div style={S.rowSub}>
                    {p.sets.length} set{p.sets.length === 1 ? '' : 's'}
                    {p.contact && ` · ${p.contact}`}
                  </div>
                </div>
                <div style={{ textAlign: 'right' }}>
                  <div style={{ fontFamily: sans, fontSize: 18, color: colors.text }}>{rupees(p.generatedInr)}</div>
                  <div style={{ fontFamily: sans, fontSize: 11, color: p.paidInr > 0 ? colors.success : colors.muted, marginTop: 2 }}>
                    {p.paidInr > 0 ? `${rupees(p.paidInr)} sent` : 'nothing sent yet'}
                  </div>
                </div>
              </div>

              <div style={{ display: 'flex', gap: 8, marginTop: 12, flexWrap: 'wrap', borderTop: `1px solid ${colors.border}`, paddingTop: 10 }}>
                <button onClick={() => setOpen(open === p.id ? null : p.id)}
                        style={{ ...S.ghostBtn, fontSize: 11, padding: '5px 10px' }}>
                  {open === p.id ? 'Hide sets' : 'Sets'}
                </button>
                <button onClick={() => openPayment(p)}
                        style={{ ...S.ghostBtn, fontSize: 11, padding: '5px 10px', color: colors.accent }}>
                  {paying === p.id ? 'Cancel' : 'Log a payment'}
                </button>
              </div>

              {open === p.id && (
                <div style={{ marginTop: 12, display: 'grid', gap: 6 }}>
                  {p.sets.map((s) => (
                    <div key={s.setId} style={setRow}>
                      <div style={{ flex: 1, minWidth: 180 }}>
                        <div style={{ fontFamily: sans, fontSize: 13, color: colors.text }}>{s.title}</div>
                        <div style={{ fontFamily: mono, fontSize: 10, color: colors.muted, marginTop: 2 }}>
                          {s.sharedWith && `shared with ${s.sharedWith - 1} other${s.sharedWith === 2 ? '' : 's'} · `}
                          {s.unlocks} unlock{s.unlocks === 1 ? '' : 's'}
                          {s.creditUnlocks > 0 && ` · ${s.creditUnlocks} on a membership`}
                          {s.giftedTokens > 0 && ` · ${s.giftedTokens} gifted tokens, not counted`}
                        </div>
                      </div>
                      <div style={{ textAlign: 'right', fontFamily: sans, fontSize: 12 }}>
                        <div style={{ color: colors.text }}>{rupees(s.revenueInr)}</div>
                        <div style={{ color: colors.muted, fontSize: 10, marginTop: 2 }}>
                          {s.purchasedTokens} token{s.purchasedTokens === 1 ? '' : 's'} spent
                        </div>
                      </div>
                    </div>
                  ))}
                </div>
              )}

              {paying === p.id && (
                <div style={payBox}>
                  <div style={S.formGrid}>
                    <Field label="Amount sent (₹)">
                      <input style={S.input} type="number" min="1" value={form.amountInr}
                             onChange={(e) => setForm({ ...form, amountInr: e.target.value })}
                             placeholder="e.g. 2500" />
                    </Field>
                    <Field label="Reference or UTR">
                      <input style={S.input} value={form.reference}
                             onChange={(e) => setForm({ ...form, reference: e.target.value })}
                             placeholder="From your bank" />
                    </Field>
                    <Field label="Note (optional)">
                      <input style={S.input} value={form.note}
                             onChange={(e) => setForm({ ...form, note: e.target.value })}
                             placeholder="What this covers" />
                    </Field>
                  </div>
                  <button onClick={() => record(p)} disabled={busy || !form.amountInr}
                          style={{ ...S.btn, marginTop: 12, opacity: (busy || !form.amountInr) ? 0.5 : 1 }}>
                    {busy ? 'Saving…' : 'Record it'}
                  </button>

                  {(history[p.id] || []).length > 0 && (
                    <div style={{ marginTop: 16, borderTop: `1px solid ${colors.border}`, paddingTop: 12 }}>
                      <div style={pLabel}>Previously sent</div>
                      {history[p.id].map((h) => (
                        <div key={h.id} style={{ fontFamily: sans, fontSize: 12, color: colors.muted, marginTop: 6 }}>
                          {rupees(h.amount_inr)} · {new Date(h.paid_at).toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' })}
                          {h.reference && ` · ${h.reference}`}
                          {h.note && ` · ${h.note}`}
                        </div>
                      ))}
                    </div>
                  )}
                </div>
              )}
            </Card>
          ))}
        </div>
      )}
    </div>
  );
}

const pLabel = { fontFamily: mono, fontSize: 10, color: colors.muted, letterSpacing: '0.1em', textTransform: 'uppercase', marginBottom: 8 };
const pValue = { fontFamily: display, fontSize: 28, color: colors.text, fontWeight: 300 };
const pSub   = { fontFamily: sans, fontSize: 11, color: colors.muted, marginTop: 6, lineHeight: 1.5 };
const setRow = { display: 'flex', justifyContent: 'space-between', alignItems: 'center', gap: 12, flexWrap: 'wrap', background: 'rgba(255,255,255,0.02)', border: `1px solid ${colors.border}`, borderRadius: 8, padding: '10px 12px' };
const payBox = { marginTop: 12, background: 'rgba(193,125,74,0.05)', border: '1px solid rgba(193,125,74,0.2)', borderRadius: 8, padding: 16 };